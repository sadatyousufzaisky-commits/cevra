const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('cevra', {
  about: () => ipcRenderer.invoke('cevra:about'),
  initial: () => ipcRenderer.invoke('cevra:initial'),
  appearance: () => ipcRenderer.invoke('cevra:appearance'),
  setTheme: choice => ipcRenderer.invoke('cevra:set-theme', choice),
  openIntelligenceMock: selection => ipcRenderer.invoke('cevra:open-intelligence-mock', selection),
  intelligenceDocumentClosed: (id, path) => ipcRenderer.send('cevra:intelligence-document-closed', id, path),
  onIntelligenceEditorSnapshot: callback => ipcRenderer.on('cevra:intelligence-editor-snapshot', async (_event, request) => {
    let snapshot = null;
    try { snapshot = await callback(request); } catch {}
    await ipcRenderer.invoke('cevra:intelligence-editor-snapshot', request.requestId, snapshot).catch(() => {});
  }),
  onIntelligencePatchSnapshot: callback => ipcRenderer.on('cevra:intelligence-patch-snapshot', async (_event, request) => {
    let snapshot = null;
    try { snapshot = await callback(request); } catch {}
    await ipcRenderer.invoke('cevra:intelligence-patch-snapshot', request.requestId, snapshot).catch(() => {});
  }),
  onIntelligenceProposalChanged: callback => ipcRenderer.on('cevra:intelligence-proposal-changed', (_event, proposal) => callback(proposal)),
  onIntelligenceTestActive: callback => ipcRenderer.on('cevra:intelligence-test-active', (_event, active) => callback(active)),
  intelligenceProposal: (id, proposalId) => ipcRenderer.invoke('cevra:intelligence-proposal', id, proposalId),
  dismissIntelligenceProposal: (id, proposalId) => ipcRenderer.invoke('cevra:dismiss-intelligence-proposal', id, proposalId),
  onIntelligenceSourceLocation: callback => ipcRenderer.on('cevra:intelligence-source-location', async (_event, request) => {
    let opened = false;
    try { opened = await callback(request); } catch {}
    await ipcRenderer.invoke('cevra:intelligence-source-location', request.requestId, opened).catch(() => {});
  }),
  extensionContributions: () => ipcRenderer.invoke('cevra:extension-contributions'),
  setExtensionPalette: key => ipcRenderer.invoke('cevra:set-extension-palette', key),
  onExtensionContributionsChanged: callback => ipcRenderer.on('cevra:extension-contributions-changed', (_event, id) => callback(id)),
  extensionRuntime: (id, includeCatalog) => ipcRenderer.invoke('cevra:extension-runtime', id, includeCatalog),
  selectExtensionPackage: () => ipcRenderer.invoke('cevra:select-extension-package'),
  inspectInstalledExtension: (id, digest) => ipcRenderer.invoke('cevra:inspect-installed-extension', id, digest),
  installExtension: (token, approveDowngrade) => ipcRenderer.invoke('cevra:install-extension', token, approveDowngrade),
  discardExtensionReview: token => ipcRenderer.invoke('cevra:discard-extension-review', token),
  changeExtension: (id, digest, action) => ipcRenderer.invoke('cevra:change-extension', id, digest, action),
  restartExtensions: disabled => ipcRenderer.invoke('cevra:restart-extensions', disabled),
  activateExtension: (id, extensionId, digest) => ipcRenderer.invoke('cevra:activate-extension', id, extensionId, digest),
  revokeExtension: (id, extensionId) => ipcRenderer.invoke('cevra:revoke-extension', id, extensionId),
  extensionCommand: (id, extensionId, commandId) => ipcRenderer.invoke('cevra:extension-command', id, extensionId, commandId),
  extensionProposal: (id, extensionId, proposalId) => ipcRenderer.invoke('cevra:extension-proposal', id, extensionId, proposalId),
  extensionDocumentChanged: (id, path) => ipcRenderer.send('cevra:extension-document-changed', id, path),
  onExtensionRuntimeChanged: callback => ipcRenderer.on('cevra:extension-runtime-changed', () => callback()),
  onExtensionEditorSnapshot: callback => ipcRenderer.on('cevra:extension-editor-snapshot', async (_event, request) => {
    let snapshot = null;
    try { snapshot = await callback(request); } catch {}
    await ipcRenderer.invoke('cevra:extension-editor-snapshot', request.requestId, snapshot).catch(() => {});
  }),
  editorSettings: id => ipcRenderer.invoke('cevra:editor-settings', id),
  setEditorSettings: (id, scope, values) => ipcRenderer.invoke('cevra:set-editor-settings', id, scope, values),
  workspaceTrust: id => ipcRenderer.invoke('cevra:workspace-trust', id),
  revokeTrust: id => ipcRenderer.invoke('cevra:revoke-trust', id),
  authorizeRun: (id, runId) => ipcRenderer.invoke('cevra:authorize-run', id, runId),
  onColorMode: callback => ipcRenderer.on('cevra:color-mode', (_event, mode) => callback(mode)),
  chooseFolder: discard => ipcRenderer.invoke('cevra:choose-folder', discard),
  openExample: discard => ipcRenderer.invoke('cevra:open-example', discard),
  confirmDiscard: name => ipcRenderer.invoke('cevra:discard', name),
  list: (id, folder) => ipcRenderer.invoke('cevra:list', id, folder),
  read: (id, file) => ipcRenderer.invoke('cevra:read', id, file),
  syntax: (id, file, text) => ipcRenderer.invoke('cevra:syntax', id, file, text),
  format: (id, file, text, eol, bom) => ipcRenderer.invoke('cevra:format', id, file, text, eol, bom),
  quickInfo: (id, file, position, buffers) => ipcRenderer.invoke('cevra:quick-info', id, file, position, buffers),
  complete: (id, file, position, buffers) => ipcRenderer.invoke('cevra:complete', id, file, position, buffers),
  signatureHelp: (id, file, position, buffers) => ipcRenderer.invoke('cevra:signature-help', id, file, position, buffers),
  definition: (id, file, position, buffers) => ipcRenderer.invoke('cevra:definition', id, file, position, buffers),
  references: (id, file, position, buffers, requestId) => ipcRenderer.invoke('cevra:references', id, file, position, buffers, requestId),
  cancelReferences: (id, requestId) => ipcRenderer.invoke('cevra:cancel-references', id, requestId),
  symbols: (id, query, buffers, requestId) => ipcRenderer.invoke('cevra:symbols', id, query, buffers, requestId),
  cancelSymbols: (id, requestId) => ipcRenderer.invoke('cevra:cancel-symbols', id, requestId),
  search: (id, request, query, caseSensitive, snapshots) =>
    ipcRenderer.invoke('cevra:search', id, request, query, caseSensitive, snapshots),
  cancelSearch: (id, request) => ipcRenderer.invoke('cevra:cancel-search', id, request),
  stageEdits: (id, changes, authority) => ipcRenderer.invoke('cevra:stage-edits', id, changes, authority),
  rename: (id, file, position, buffers, name) => ipcRenderer.invoke('cevra:rename', id, file, position, buffers, name),
  typeCheck: (id, file, buffers) => ipcRenderer.invoke('cevra:type-check', id, file, buffers),
  save: (id, file, text, revision) => ipcRenderer.invoke('cevra:save', id, file, text, revision),
  saveCopy: (id, file, text) => ipcRenderer.invoke('cevra:save-copy', id, file, text),
  draft: (id, file, text, revision) => ipcRenderer.invoke('cevra:draft', id, file, text, revision),
  start: (id, file, revision, runId, token, profile) => ipcRenderer.invoke('cevra:start', id, file, revision, runId, token, profile),
  debugStart: (id, file, revision, runId, token, breakpoints) => ipcRenderer.invoke('cevra:debug-start', id, file, revision, runId, token, breakpoints),
  debugCommand: (id, runId, token, action, pauseId, frame) => ipcRenderer.invoke('cevra:debug-command', id, runId, token, action, pauseId, frame),
  pythonProfiles: id => ipcRenderer.invoke('cevra:python-profiles', id),
  choosePython: id => ipcRenderer.invoke('cevra:choose-python', id),
  test: (id, retry, runId, token, goal) => ipcRenderer.invoke('cevra:test', id, retry, runId, token, goal),
  runEvidence: (id, evidenceId) => ipcRenderer.invoke('cevra:run-evidence', id, evidenceId),
  taskCatalog: id => ipcRenderer.invoke('cevra:task-catalog', id),
  runTask: (id, target, revision, runId, token) => ipcRenderer.invoke('cevra:run-task', id, target, revision, runId, token),
  recipeCatalog: id => ipcRenderer.invoke('cevra:recipes', id),
  recipePreview: (id, recipeId) => ipcRenderer.invoke('cevra:recipe-preview', id, recipeId),
  recipeFile: (id, action, revision) => ipcRenderer.invoke('cevra:recipe-file', id, action, revision),
  authorizeRecipe: (id, runId, recipeId, digest) => ipcRenderer.invoke('cevra:authorize-recipe', id, runId, recipeId, digest),
  recipeStart: (id, runId, token, breakpoints, goal) => ipcRenderer.invoke('cevra:recipe-start', id, runId, token, breakpoints, goal),
  flightpath: (id, action) => ipcRenderer.invoke('cevra:flightpath', id, action),
  gitStatus: id => ipcRenderer.invoke('cevra:git-status', id),
  gitDiff: (id, snapshot, file, side) => ipcRenderer.invoke('cevra:git-diff', id, snapshot, file, side),
  gitReview: (id, snapshot) => ipcRenderer.invoke('cevra:git-review', id, snapshot),
  gitWrite: (id, action, details) => ipcRenderer.invoke('cevra:git-write', id, action, details),
  stop: (id, runId, sessionId) => ipcRenderer.invoke('cevra:stop', id, runId, sessionId),
  runOutput: (id, runId, sessionId, cursor) => ipcRenderer.invoke('cevra:run-output', id, runId, sessionId, cursor),
  terminalNew: (id, profile, columns, rows) => ipcRenderer.invoke('cevra:terminal-new', id, profile, columns, rows),
  terminalRead: (id, sessionId) => ipcRenderer.invoke('cevra:terminal-read', id, sessionId),
  terminalWrite: (id, sessionId, text) => ipcRenderer.invoke('cevra:terminal-write', id, sessionId, text),
  terminalResize: (id, sessionId, columns, rows) => ipcRenderer.invoke('cevra:terminal-resize', id, sessionId, columns, rows),
  terminalClose: (id, sessionId) => ipcRenderer.invoke('cevra:terminal-close', id, sessionId),
  terminalCopy: (id, sessionId, text) => ipcRenderer.invoke('cevra:terminal-copy', id, sessionId, text),
  terminalPaste: (id, sessionId) => ipcRenderer.invoke('cevra:terminal-paste', id, sessionId),
  ready: () => ipcRenderer.send('cevra:ready'),
  closeReady: (hasDrafts, backupFailed) => ipcRenderer.invoke('cevra:close-ready', hasDrafts, backupFailed),
  beforeClose: callback => ipcRenderer.on('cevra:before-close', () => callback()),
  onCloseCanceled: callback => ipcRenderer.on('cevra:close-canceled', () => callback()),
  onRun: callback => ipcRenderer.on('cevra:run-event', (_event, detail) => callback(detail)),
});
